"""
Custom Scenario Upload & Run -- lets externally-created scenario data (built
by hand, or generated by any outside tool) run through the real Stage 1-5
(+8) pipeline without an internal AI-generation step.

Two input paths:
  1. CSV, schema-matching -- validate_csv_files() checks columns and types
     against the real schema (read directly from data/raw/*.csv -- there is
     no separate "BRD Section 5" document in this repo, the schema below IS
     the ground truth, same conclusion as the "BRD Section 18" question
     earlier: verify against what actually exists, not what's assumed to).
  2. Free text -- extract_from_text() makes one real LLM call (reusing the
     exact same provider chain as Stage 8: Claude -> Gemini, no template
     fallback here, since unlike a case writeup there is no honest
     deterministic equivalent for open-ended text extraction) to turn a
     plain-language description into the same structured schema, for the
     caller to show the user before running anything.

Isolation, verified the same way as every other feature this week: never
writes to data/raw/*.csv, data/frozen_snapshot/, or data/app.db.
run_scenario() copies the real data/raw/ into a disposable tempdir
(read-only source, exactly the pattern already used by
adversarial_stress_test.py and adversarial_recommender/gap_characterizer.py),
appends the uploaded/extracted rows there, and runs the pipeline against
that copy only.

Run standalone (CSV path only -- free text needs the dashboard): none;
this module is designed to be called from frontend/app_pages/live_injection.py.
"""

